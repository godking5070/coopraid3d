param(
    [Parameter(Mandatory = $true)][string]$OriginalProject,
    [string]$Compiler
)

$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path $PSScriptRoot -Parent
$OriginalProject = (Resolve-Path -LiteralPath $OriginalProject).Path

if (!$Compiler) {
    $taskVsWhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
    if (Test-Path -LiteralPath $taskVsWhere) {
        $Compiler = (& $taskVsWhere -latest -products '*' -find 'MSBuild/**/Bin/Roslyn/csc.exe' | Select-Object -First 1)
    }
}
if (!$Compiler -or !(Test-Path -LiteralPath $Compiler)) {
    throw 'Pass -Compiler with the path to a C# 9+ csc.exe.'
}

$taskOutput = Join-Path ([IO.Path]::GetTempPath()) ('Astella-2D-Managed-' + [Guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($taskOutput) | Out-Null
Write-Output "Managed validation output: $taskOutput"
Write-Output 'Managed compilation checks C# sources and references only; it is not Unity import, Play Mode, or rendering verification.'

# Run only the standalone 2D geometry checks. The broader 3D combat suites are
# deliberately not invoked by this entry point.
& (Join-Path $PSScriptRoot 'Run-Astella2DChecks.ps1') -Compiler $Compiler
if ($LASTEXITCODE -ne 0) { throw 'Astella 2D geometry checks failed.' }

# Read references and platform defines generated by the original Unity project,
# while enumerating current source files so newly added 2D code is included even
# before Unity can regenerate its project files. This never launches the editor,
# copies Library, restores packages, or changes the generated csproj files.
if (Get-Command rg -ErrorAction SilentlyContinue) {
    $taskSources = @(& rg --files (Join-Path $taskRoot 'Assets') -g '*.cs')
    if ($LASTEXITCODE -ne 0) { $taskSources = @() }
} else {
    $taskSources = @(Get-ChildItem -LiteralPath (Join-Path $taskRoot 'Assets') -Recurse -File -Filter '*.cs' | ForEach-Object FullName)
}
if (!$taskSources.Count) { throw 'Could not enumerate the project C# sources.' }

foreach ($taskAssembly in @('Assembly-CSharp', 'Assembly-CSharp-Editor')) {
    $taskProjectPath = Join-Path $OriginalProject "$taskAssembly.csproj"
    if (!(Test-Path -LiteralPath $taskProjectPath)) {
        throw "Missing original Unity project file: $taskProjectPath"
    }
    [xml]$taskProject = Get-Content -LiteralPath $taskProjectPath -Raw -Encoding UTF8
    $taskDefinesNode = $taskProject.SelectSingleNode("//*[local-name()='DefineConstants']")
    if (!$taskDefinesNode) { throw "Missing compiler defines in $taskProjectPath" }
    $taskDefines = $taskDefinesNode.InnerText
    $taskLines = @(
        '/nologo', '/nostdlib+', '/langversion:9.0', '/target:library', '/utf8output',
        "/define:$taskDefines", "/out:`"$(Join-Path $taskOutput "$taskAssembly.dll")`""
    )

    foreach ($taskReference in $taskProject.SelectNodes("//*[local-name()='Reference']/*[local-name()='HintPath']")) {
        $taskRefPath = $taskReference.InnerText
        if (![IO.Path]::IsPathRooted($taskRefPath)) { $taskRefPath = Join-Path $OriginalProject $taskRefPath }
        if ([IO.Path]::GetFileName($taskRefPath) -eq 'Assembly-CSharp.dll') { continue }
        if ($env:RAIDROGUE_STEAM_REFERENCE -and [IO.Path]::GetFileName($taskRefPath) -eq 'com.rlabrecque.steamworks.net.dll') { continue }
        if ($env:RAIDROGUE_TRANSPORT_REFERENCE -and [IO.Path]::GetFileName($taskRefPath) -eq 'Unity.Networking.Transport.dll') { continue }
        if (!(Test-Path -LiteralPath $taskRefPath)) { throw "Missing original project reference: $taskRefPath" }
        $taskLines += "/reference:`"$taskRefPath`""
    }
    if ($env:RAIDROGUE_TRANSPORT_REFERENCE) { $taskLines += "/reference:`"$env:RAIDROGUE_TRANSPORT_REFERENCE`"" }
    if ($env:RAIDROGUE_STEAM_REFERENCE) { $taskLines += "/reference:`"$env:RAIDROGUE_STEAM_REFERENCE`"" }

    $taskEditor = $taskAssembly -eq 'Assembly-CSharp-Editor'
    if ($taskEditor) { $taskLines += "/reference:`"$(Join-Path $taskOutput 'Assembly-CSharp.dll')`"" }
    $taskAssemblySources = @($taskSources | Where-Object { ($_ -match '[/\\]Editor[/\\]') -eq $taskEditor })
    foreach ($taskSource in $taskAssemblySources) { $taskLines += "`"$taskSource`"" }

    $taskResponse = Join-Path $taskOutput "$taskAssembly.rsp"
    [IO.File]::WriteAllLines($taskResponse, $taskLines, [Text.UTF8Encoding]::new($false))
    & $Compiler /noconfig "@$taskResponse"
    if ($LASTEXITCODE -ne 0) { throw "$taskAssembly managed compilation failed." }
    Write-Output "PASS: $taskAssembly managed compilation ($($taskAssemblySources.Count) current source files)."
}

Write-Output 'PASS: Astella 2D geometry and both managed assemblies. Unity editor and actual Play verification remain separate.'
