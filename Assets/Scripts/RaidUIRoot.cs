using System;
using System.Collections;
using System.Collections.Generic;
using UnityEngine;

namespace RaidRogue
{
    [DefaultExecutionOrder(-31000)]
    public sealed class RaidUIRoot : MonoBehaviour
    {
        [Serializable] public sealed class PresenterBinding
        {
            public string typeName;
            public MonoBehaviour embeddedPresenter;
            public List<RaidUIView.Reference> references = new List<RaidUIView.Reference>();
        }
        [Tooltip("UI references to scene gameplay presenters. Generated by the editor; independent of hierarchy names.")]
        public List<PresenterBinding> presenters = new List<PresenterBinding>();
        private bool _connected;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        private static void Install()
        {
            var authored = FindFirstObjectByType<RaidUIRoot>();
            if (authored != null) { authored.Connect(); return; }
            var prefab = RaidUIPresentation.Settings?.hudPrefab;
            if (prefab == null) return;
            var old = FindFirstObjectByType<SkillHotbarUI>()?.GetComponentInParent<Canvas>();
            if (old == null) return; // Not a raid scene.
            old.gameObject.SetActive(false);
            RaidUIView.ReleaseOwners();
            var root = Instantiate(prefab); root.name = prefab.name; root.Connect();
            Destroy(old.gameObject);
        }
        private void Start() { Connect(); }
        public void Connect()
        {
            if (_connected) return; _connected = true;
            // Older authored HUDs remain usable until the editable minimap is saved.
            if (GetComponentInChildren<RaidMinimapUI>(true) == null)
                RaidMinimapUI.CreateDefault(transform);
            var bridge = gameObject.AddComponent<RaidUIView>(); bridge.viewId = "scene-bindings";
            var deferred = new List<PresenterBinding>();
            foreach (var binding in presenters)
            {
                if (!RestorePresenter(binding, bridge)) deferred.Add(binding);
            }
            Destroy(bridge);
            // The raid managers add several presenters in Start. AfterSceneLoad runs
            // before those components exist; retry once after Start, not every frame.
            if (deferred.Count > 0) StartCoroutine(RestoreDeferredPresenters(deferred));
            // World references cannot be saved in a UI prefab. Resolve the local presentation owners once.
            var combat = FindFirstObjectByType<PlayerCombatController>();
            foreach (var hotbar in GetComponentsInChildren<SkillHotbarUI>(true)) hotbar.combatController = combat;
            foreach (var party in GetComponentsInChildren<PartyListUI>(true)) party.RefreshPartyReferences();
        }
        private static bool RestorePresenter(PresenterBinding binding, RaidUIView bridge)
        {
            var type = Type.GetType(binding.typeName);
            var owner = binding.embeddedPresenter != null ? binding.embeddedPresenter : type != null ? FindFirstObjectByType(type) as MonoBehaviour : null;
            if (owner == null) return false;
            bridge.references = binding.references; bridge.Restore(owner);
            // The editable HUD can restore button references after the presenter's Start.
            // Bind to the restored buttons rather than listeners on the discarded canvas.
            if (owner is RoguelikeCardManager cards) cards.BindCardButtons();
            if (owner is CombatMetricsUI metrics) metrics.BindResultButtons();
            return true;
        }
        private IEnumerator RestoreDeferredPresenters(List<PresenterBinding> deferred)
        {
            yield return null;
            var bridge = gameObject.AddComponent<RaidUIView>(); bridge.viewId = "scene-bindings";
            foreach (var binding in deferred)
                if (!RestorePresenter(binding, bridge)) Debug.LogWarning("UI presenter unavailable after startup: " + binding.typeName, this);
            Destroy(bridge);
        }
    }
}
